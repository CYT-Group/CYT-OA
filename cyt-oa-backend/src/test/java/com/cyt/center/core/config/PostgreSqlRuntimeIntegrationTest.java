/** 显式传入一次性测试库连接；所有写入只发生在临时表，连接关闭前回滚。 */
class PostgreSqlRuntimeIntegrationTest {
    private Connection connection;
    private SingleConnectionDataSource source;
    private JdbcTemplate jdbc;

    @BeforeEach void connect() throws Exception {
        String url = System.getenv("CYT_TEST_PG_URL");
        assumeTrue(url != null && url.startsWith("jdbc:postgresql:"), "未配置一次性 PostgreSQL 测试库");
        if (!url.contains("stringtype=")) url += (url.contains("?") ? "&" : "?") + "stringtype=unspecified";
        connection = DriverManager.getConnection(url,
                System.getenv().getOrDefault("CYT_TEST_PG_USERNAME", "postgres"),
                System.getenv().getOrDefault("CYT_TEST_PG_PASSWORD", ""));
        connection.setAutoCommit(false);
        source = new SingleConnectionDataSource(connection, true);
        jdbc = new PostgreSqlJdbcConfiguration.NumericBooleanJdbcTemplate(source);
    }

    @AfterEach void close() throws Exception {
        if (connection != null) {
            connection.rollback();
            connection.close();
        }
    }

    @Test void mybatisPersistsBooleanAndSoftDeletesUsingNumericColumns() throws Exception {
        jdbc.execute("CREATE TEMP TABLE pg_runtime_probe(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, active SMALLINT, deleted SMALLINT DEFAULT 0)");
        var configuration = new MybatisConfiguration();
        new MybatisPlusConfig().numericBooleanTypeCustomizer().customize(configuration);
        configuration.addMapper(ProbeMapper.class);
        var factory = new MybatisSqlSessionFactoryBean();
        factory.setDataSource(source);
        factory.setConfiguration(configuration);
        try (var session = factory.getObject().openSession()) {
            var mapper = session.getMapper(ProbeMapper.class);
            var row = new Probe();
            row.setActive(true);
            row.setDeleted(false);
            assertEquals(1, mapper.insert(row));
            assertNotNull(row.getId());
            assertEquals(Boolean.TRUE, mapper.selectById(row.getId()).getActive());
            assertEquals(1, mapper.selectCount(new QueryWrapper<Probe>().eq("active", true)));
            assertEquals(0, mapper.selectCount(new QueryWrapper<Probe>().eq("active", false)));
            var projection = new MPJLambdaWrapperX<Probe>().selectAs(Probe::getId, "\"probeId\"");
            var projected = jdbc.queryForMap("SELECT " + projection.getSqlSelect() + " FROM pg_runtime_probe t");
            assertEquals(row.getId(), projected.get("probeId"));
            assertEquals(1, mapper.deleteById(row.getId()));
            assertNull(mapper.selectById(row.getId()));
            assertEquals(1, jdbc.queryForObject("SELECT deleted FROM pg_runtime_probe WHERE id=?", Integer.class, row.getId()));
        }
    }

    @Test void repositoriesReturnOneGeneratedIdAndHandleRepeatedUpserts() {
        jdbc.execute("CREATE TEMP TABLE portal_workspace_records(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,kind TEXT,record_key TEXT,owner_id BIGINT,dept_id BIGINT,parent_id BIGINT,title TEXT,status TEXT,payload TEXT,version INT DEFAULT 1,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)");
        var store = new PortalWorkspaceStore(jdbc, new ObjectMapper());
        long id = store.insert("objective", "probe", 42, null, null, "目标", "active", Map.of("period", "2026-Q4"));
        assertTrue(id > 0);
        assertEquals("2026-Q4", store.get("objective", id, false).data().get("period"));

        jdbc.execute("CREATE TEMP TABLE portal_entry_rollout(id BIGINT PRIMARY KEY,entries TEXT,revision BIGINT,updated_by TEXT,updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)");
        var rollout = new PortalEntryRolloutRepository(jdbc, new ObjectMapper());
        rollout.initialize();
        rollout.initialize();
        assertTrue(rollout.update(Map.of("training", true), 0, "probe"));
        assertFalse(rollout.update(Map.of("training", false), 0, "probe"));
        assertEquals(Boolean.TRUE, rollout.read(false).entries().get("training"));

        jdbc.execute("CREATE TEMP TABLE portal_celebration_preferences(user_id BIGINT PRIMARY KEY,opt_out SMALLINT)");
        jdbc.execute("CREATE TEMP TABLE portal_celebration_runs(run_date DATE,kind TEXT,status TEXT,UNIQUE(run_date,kind))");
        var celebrations = new PortalCelebrationRepository(jdbc);
        celebrations.preference(42, true);
        celebrations.preference(42, false);
        assertEquals(0, jdbc.queryForObject("SELECT opt_out FROM portal_celebration_preferences WHERE user_id=42", Integer.class));
        assertTrue(celebrations.claim(LocalDate.of(2026, 11, 12), "daily"));
        assertFalse(celebrations.claim(LocalDate.of(2026, 11, 12), "daily"));
    }

    @Test void dateJsonMembershipAndLimitedDeletionUsePostgresSemantics() {
        jdbc.execute("CREATE TEMP TABLE pg_runtime_probe(id BIGINT PRIMARY KEY,occurred_at TIMESTAMP,finished_at TIMESTAMP,ids TEXT,payload TEXT)");
        jdbc.update("INSERT INTO pg_runtime_probe VALUES(1,'2026-11-12 08:09:10','2026-11-14 20:00:00','1,11','[1,11]')");
        var row = jdbc.queryForMap("SELECT " + SqlDialectUtils.formatDate("occurred_at") + " AS day," +
                SqlDialectUtils.formatYearMonth("occurred_at") + " AS month," +
                SqlDialectUtils.month("occurred_at") + " AS month_number," +
                SqlDialectUtils.findInSetColumn("id", "ids") + " AS member," +
                SqlDialectUtils.jsonArrayContains("payload", true).replace("{0}", "?") +
                " AS contained,occurred_at AS \"createdAt\" FROM pg_runtime_probe", 11L);
        assertEquals("2026-11-12", row.get("day"));
        assertEquals("202611", row.get("month"));
        assertEquals(11, ((Number) row.get("month_number")).intValue());
        assertEquals(true, row.get("member"));
        assertEquals(true, row.get("contained"));
        assertTrue(row.containsKey("createdAt"));
        assertEquals(2.0, jdbc.queryForObject("SELECT " + SqlDialectUtils.customerDealCycle("occurred_at", "finished_at") + " FROM pg_runtime_probe", Double.class));
        assertEquals(1, jdbc.queryForObject("SELECT COUNT(*) FROM pg_runtime_probe WHERE " + MyBatisUtils.findInSet("ids").replace("{0}", "?"), Integer.class, 1));
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM pg_runtime_probe WHERE " + MyBatisUtils.findInSet("ids").replace("{0}", "?"), Integer.class, 2));
        String deletion = SqlDialectUtils.deleteBatchByLessThan("pg_runtime_probe", "id", "cutoff", "batch")
                .replace("#{cutoff}", "?").replace("#{batch}", "?");
        assertEquals(1, jdbc.update(deletion, 5, 1));
    }

    @Test void stringDatesAndJsonAggregatesPreserveRepositoryResponseTypes() {
        jdbc.execute("CREATE TEMP TABLE pg_date_probe(birth_date DATE)");
        jdbc.update("INSERT INTO pg_date_probe VALUES(?)", "2000-11-12");
        assertEquals(LocalDate.of(2000, 11, 12), jdbc.queryForObject("SELECT birth_date FROM pg_date_probe", LocalDate.class));

        jdbc.execute("CREATE TEMP TABLE sys_user(id BIGINT PRIMARY KEY,username TEXT,name TEXT,main_dept_id BIGINT,enabled SMALLINT)");
        jdbc.execute("CREATE TEMP TABLE sys_dept(id BIGINT PRIMARY KEY,name TEXT,active SMALLINT)");
        jdbc.execute("CREATE TEMP TABLE sys_user_dept(user_id BIGINT,dept_id BIGINT)");
        jdbc.update("INSERT INTO sys_dept VALUES(1,'研发',1),(2,'产品',1)");
        jdbc.update("INSERT INTO sys_user VALUES(42,'probe','测试员工',1,?)", true);
        jdbc.update("INSERT INTO sys_user_dept VALUES(42,2)");
        var editor = new PortalHrEditorRepository(jdbc, new ObjectMapper());
        var users = editor.searchPushUsers("测试");
        assertEquals(1, users.size());
        assertEquals("测试员工", users.getFirst().get("displayName"));
        assertEquals(true, users.getFirst().get("isActive"));
        assertTrue(users.getFirst().get("department") instanceof List<?>);
        assertEquals(2, ((List<?>) users.getFirst().get("department")).size());
        assertEquals(1, editor.departmentStats().getFirst().get("userCount"));
    }

    @Data
    @TableName("pg_runtime_probe")
    public static class Probe {
        @TableId(type = IdType.AUTO) private Long id;
        private Boolean active;
        @TableLogic private Boolean deleted;
    }

    public interface ProbeMapper extends BaseMapper<Probe> {}
}
